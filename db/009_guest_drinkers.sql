--  מוזמנים · כמה מהם שותים אלכוהול
--  ---------------------------------------------------------------------
--  מחשבון האלכוהול צריך לדעת כמה אנשים בפועל שותים, לא כמה כיסאות הוזמנו.
--  רשומה אחת ברשימה מייצגת לא פעם משפחה שלמה ("משפחת כהן, 4 כיסאות"), ולכן
--  דגל בוליאני היה מאבד את ההבחנה בין זוג שבו שניהם שותים לבין זוג שבו אחד
--  שותה. עמודה מספרית נותנת את שתי התשובות: 0 = לא שותים, וכל מספר אחר הוא
--  מספר השותים באותה רשומה.
--
--  ברירת המחדל היא 0 ולא seats במכוון: אף אחד עוד לא סימן דבר, וניחוש
--  אוטומטי היה מייצר מספרים שנראים כמו נתון אמיתי. המחשבון מציע במקום זה
--  הערכה לפי אחוז מהאורחים, וברור בו שזו הערכה.


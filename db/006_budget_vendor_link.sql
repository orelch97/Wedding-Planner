-- =============================================================================
--  005_budget_vendor_link.sql — קישור סעיף תקציב לספק
-- -----------------------------------------------------------------------------
--  עד כה "ניהול תקציב" ו"ספקים ומשימות" היו שני עולמות נפרדים: אפשר היה לסגור
--  ספק ב-40,000 ₪ ולא לראות את הסכום בתקציב כלל, או להזין אותו ידנית פעמיים
--  ואז לא לדעת איזה מספר נכון. העמודה הזו הופכת סעיף תקציב לסעיף שנוצר מספק,
--  כך שהמערכת יכולה ליצור אותו אוטומטית, לגרור אחריו שינויי שם ועלות, ולסמן
--  במסך כשהסכום בתקציב שונה מהעלות בחוזה.
--
--  ההגדרה מכוונת:
--    * NULL = סעיף שהוקלד ידנית. כל הסעיפים הקיימים נשארים כאלה.
--    * אין FOREIGN KEY אל public.vendors בכוונה. מחיקת ספק היא "מחיקה רכה"
--      (deleted_at) ולא מחיקת שורה, ולכן מפתח זר לא היה מנקה כלום; מנגד הוא
--      היה חוסם את סנכרון הלקוח כשסעיף וספק נשלחים בשתי בקשות נפרדות
--      ("ספקים" נשמר לפני "תקציב" או להפך). הקשר נאכף בקוד, ומסך התקציב
--      מתעלם משיוך לספק שאינו קיים.
-- =============================================================================

ALTER TABLE public.budget_items ADD COLUMN IF NOT EXISTS vendor_id INT8;


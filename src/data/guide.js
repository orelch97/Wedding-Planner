/*  דגלי "כבר ראיתי את זה".
 *  לא עוברים דרך usePersistentState כי חלק מהם נקראים במסך ההתחברות,
 *  לפני שיש בכלל משתמש או חתונה שאפשר לתלות בהם מפתח.
 */
const FLAG_PREFIX = "wp:guide:";

export function guideSeen(key) {
  try {
    return localStorage.getItem(FLAG_PREFIX + key) === "1";
  } catch {
    return false; // מצב פרטי / חסימת אחסון – פשוט נציג שוב
  }
}

export function markGuideSeen(key) {
  try {
    localStorage.setItem(FLAG_PREFIX + key, "1");
  } catch {
    /* ignore */
  }
}


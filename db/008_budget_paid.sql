-- =============================================================================
--  008_budget_paid.sql — עמודת "סה״כ שולם" בסעיפי התקציב
-- -----------------------------------------------------------------------------
--  עד כה לכל סעיף תקציב היו שני סכומים בלבד: expected ("הוצאה צפויה" — האומדן
--  לפני שסוגרים) ו-actual ("הוצאה בפועל" — מה שסוכם שנדרש לשלם). לא היה שום
--  מקום לרשום כמה כבר שולם, ולכן זוג ששילם מקדמה של 20,000 ₪ מתוך 95,000 ₪
--  ראה במסך "95,000" ולא ידע מה עוד מחכה לו בחשבון הבנק.
--
--  paid = הסכום שכבר שולם בפועל. "נותר לשלם" מחושב כ-actual − paid.
--
--  מילוי לאחור: סעיף שנוצר מספק כבר מחזיק את המקדמה של אותו ספק בעמודה
--  vendors.deposit, ולכן אפשר להעתיק אותה ולחסוך למשתמשים הקיימים הקלדה
--  חוזרת. התנאי paid = 0 מגן מפני הרצה חוזרת של המיגרציה שתדרוס נתון שהוזן
--  ידנית אחריה.
-- =============================================================================

ALTER TABLE public.budget_items ADD COLUMN IF NOT EXISTS paid NUMERIC NOT NULL DEFAULT 0;

UPDATE public.budget_items AS b
   SET paid = v.deposit
  FROM public.vendors AS v
 WHERE v.wedding_id = b.wedding_id
   AND v.id = b.vendor_id
   AND b.vendor_id IS NOT NULL
   AND b.paid = 0
   AND v.deposit > 0
   AND v.deleted_at IS NULL;
